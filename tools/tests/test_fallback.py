def 地図を作る(ジャンル):
    """テスト用の、最小限の genre_roots.html を組み立てる。"""
    行 = []
    for g in ジャンル:
        行.append(
            '{id:"%s", label:"%s", rep_tracks:%s, yt_tracks:%s, yt_mix:%s},' % (
                g['id'], g['label'],
                json.dumps(g['rep_tracks'], ensure_ascii=False),
                json.dumps(g['yt_tracks'], ensure_ascii=False),
                json.dumps(g['yt_mix'], ensure_ascii=False)))
    return 'const NODES = [\n' + '\n'.join(行) + '\n];\nconst LINKS = [];\n'


def 取り出す(html, gid, 名前):
    m = re.search(r'\{id:"%s"' % gid, html)
    先 = html.find('{id:', m.start() + 4)
    塊 = html[m.start(): 先 if 先 > 0 else len(html)]
    return 本体.配列を取る(塊, 名前)[0]


